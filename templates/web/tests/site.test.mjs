import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
test('no premature automatic preview deployments',()=>{assert.equal(JSON.parse(read('vercel.json')).git.deploymentEnabled,false);});
test('public pages have explicit robots and sitemap implementations',()=>{assert.ok(fs.existsSync(path.join(root,'app/robots.ts')));assert.ok(fs.existsSync(path.join(root,'app/sitemap.ts')));});
test('no misleading real privacy policy',()=>{assert.match(read('app/privacy/page.tsx'),/Draft required/);});
